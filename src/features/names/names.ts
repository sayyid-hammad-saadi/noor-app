export const NAMES: readonly IslamicName[] = ROWS.map(
  ([id, en, ar, bn, gender, theme, syllables, pron, origin, root, verse]) => ({
    id,
    en,
    ar,
    bn,
    gender,
    theme,
    syllables,
    pron,
    origin,
    root,
    verse,
  }),
);

export function getName(id: string): IslamicName | undefined {
  return NAMES.find((n) => n.id === id);
}

/** Same root first, then same theme and gender; up to three. */
export function similarNames(name: IslamicName): IslamicName[] {
  const others = NAMES.filter((n) => n.id !== name.id);
  const byRoot = name.root ? others.filter((n) => n.root === name.root) : [];
  const rest = others.filter(
    (n) =>
      !byRoot.includes(n) &&
      n.theme === name.theme &&
      (n.gender === name.gender || n.gender === 'unisex'),
  );
  return [...byRoot, ...rest].slice(0, 3);
}

/** Letters that names start with, for the starting-letter picker. */
export function startingLetters(): string[] {
  return [...new Set(NAMES.map((n) => n.en.replace(/^'/, '')[0]!.toUpperCase()))].sort();
}
